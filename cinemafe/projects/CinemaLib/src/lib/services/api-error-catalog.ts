const EXACT = new Map<string, string>();
const PATTERNS: { key: string; pattern: RegExp }[] = [];
for (const rule of API_ERROR_RULES) {
  if (rule.exact !== undefined) {
    EXACT.set(rule.exact, rule.key);
  } else if (rule.pattern) {
    PATTERNS.push({ key: rule.key, pattern: rule.pattern });
  }
}

export interface ApiErrorMatch {
  key: string;
  params: Record<string, string>;
}

/** Finds the rule for a server message, or null when the message is not in the catalog. */
export function matchApiError(message: string): ApiErrorMatch | null {
  const text = message.trim();
  const exactKey = EXACT.get(text);
  if (exactKey) {
    return { key: exactKey, params: {} };
  }
  for (const { key, pattern } of PATTERNS) {
    const found = pattern.exec(text);
    if (found) {
      return { key, params: { ...found.groups } };
    }
  }
  return null;
}
