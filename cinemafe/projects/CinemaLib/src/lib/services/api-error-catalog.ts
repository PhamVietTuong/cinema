/**
 * Maps the API's fixed English messages to keys under `apiErrors` in the translation files.
 *
 * Managers throw plain English text and ExceptionMiddleware relays it as `{ error }`, so a Vietnamese
 * user would otherwise read English. A fixed message is listed as `exact`; one with interpolated values
 * is a `pattern` whose named groups become the interpolation params of the translation. Order matters
 * for patterns only (first match wins). A message with no rule is shown as the server sent it.
 */
export interface ApiErrorRule {
  key: string;
  exact?: string;
  pattern?: RegExp;
}

